#!/usr/bin/env python3
"""Regenerate tools/stoplist.txt from the live backlog (tools/puzzles_src.json).
Stoplisted: any answer of 4+ letters already used in 2+ live puzzles, and any answer of any length used in 3+.
CONTAINS ANSWERS (spoilers) - constructors read it, solvers should not. Run after each ingest (ingest.py does this)."""
import json,os,sys,collections
here=os.path.dirname(os.path.abspath(__file__));sys.path.insert(0,here)
import quality as Q
src=json.load(open(os.path.join(here,'puzzles_src.json')))
occ=collections.defaultdict(set)
for p in src:
    for e in Q.entries(p['grid']):occ[e['word']].add(p['id'])
stop=sorted(w for w,s in occ.items() if (len(s)>=2 and len(w)>=4) or len(s)>=3)
open(os.path.join(here,'stoplist.txt'),'w').write('# SPOILERS: overused answers - avoid in new puzzles. Generated by tools/make_stoplist.py; do not hand-edit.\n'+'\n'.join(stop)+'\n')
print(len(stop),'stoplisted answers')
